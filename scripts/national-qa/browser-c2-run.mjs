#!/usr/bin/env node
/**
 * Second Conductor / Class One E5 portable real-Chromium journey runner.
 * It never creates an account, signs a GPU proof or fakes a GameRunner.
 *
 * node scripts/national-qa/browser-c2-run.mjs --mode national-solo-desktop
 * node scripts/national-qa/browser-c2-run.mjs --mode national-solo-mobile
 * node scripts/national-qa/browser-c2-run.mjs --mode private-national
 * node scripts/national-qa/browser-c2-run.mjs --mode legacy-desktop
 * node scripts/national-qa/browser-c2-run.mjs --mode legacy-mobile
 * node scripts/national-qa/browser-c2-run.mjs --mode all
 *
 * Private requires three real Chrome profiles, already authenticated through
 * the legitimate hosted server, at NATIONAL_QA_PRIVATE_CDP_PORTS=portA,portB,portC.
 * The independent E6 host witness is NEVER generated by this process.
 */
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import {
  C2_PATHS,
  classifySoloOrLegacy,
  classifyPrivateNational,
  verifyPrivateBrowserTopology,
} from "./browser-c2-verdict.mjs";
import { inspectScreenshotFile } from "./png-evidence.mjs";

const argv = process.argv;
const mode = argv[argv.indexOf("--mode") + 1] ?? "";
const modes =
  mode === "all" ? Object.keys(C2_PATHS).concat("private-national") : [mode];
if (modes.some((name) => name !== "private-national" && !C2_PATHS[name])) {
  console.error("C2_E5_UNKNOWN_MODE");
  process.exit(2);
}
const git = spawnSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" });
const head = git.status === 0 ? git.stdout.trim() : "";
const requestedSha = process.env.NATIONAL_GPU_CANDIDATE_SHA ?? head;
if (!/^[a-f0-9]{40}$/.test(head) || requestedSha !== head) {
  console.error("C2_E5_EXACT_SOURCE_SHA_NOT_CHECKED_OUT");
  process.exit(2);
}
const realHardwareRequested = process.env.NATIONAL_REQUIRE_HARDWARE_GPU === "1";
if (
  realHardwareRequested &&
  (process.env.NATIONAL_E6_APPROVED_CANDIDATE_SHA !== head ||
    !/^[0-9]+$/.test(process.env.NATIONAL_E6_APPROVED_RUN_ID ?? ""))
) {
  console.error("C2_E5_PHYSICAL_GPU_NOT_AUTHORIZED_BY_E6");
  process.exit(2);
}
const root = resolve("national-qa-artifacts", "c2");
mkdirSync(root, { recursive: true });
const folders = {
  "national-solo-desktop": "browser-national-desktop",
  "national-solo-mobile": "browser-national-mobile",
  "legacy-desktop": "browser-legacy-ffa-desktop",
  "legacy-mobile": "browser-legacy-ffa-mobile",
};
function screenshots(folder) {
  if (!existsSync(folder)) return { labels: [], manifest: [] };
  const manifest = readdirSync(folder)
    .filter((name) => name.endsWith(".png"))
    .map((name) => ({
      name: name.slice(0, -4),
      proof: inspectScreenshotFile(join(folder, name)),
    }))
    .filter((entry) => entry.proof !== null)
    .map(({ name, proof }) => ({
      label: name,
      ...proof,
    }));
  return { labels: manifest.map((entry) => entry.label), manifest };
}
function save(modeName, verdict) {
  const path = join(root, modeName + ".json");
  writeFileSync(
    path,
    JSON.stringify(
      {
        exactSource: head,
        mode: modeName,
        ...verdict,
      },
      null,
      2,
    ) + "\n",
  );
  console.info(
    "C2_E5_VERDICT " +
      JSON.stringify({
        mode: modeName,
        gameplay: verdict.gameplay,
        hardware: verdict.hardware,
        firstFailure: verdict.firstFailure,
        firstFailedStage: verdict.firstFailedStage,
        source: head,
      }),
  );
}
function runLocal(modeName) {
  const config = C2_PATHS[modeName];
  const folder = join("national-qa-artifacts", folders[modeName]);
  if (existsSync(folder)) {
    // Never certify stale screenshot/report leftovers as a new playthrough.
    const old = readdirSync(folder);
    if (old.length) {
      const verdict = {
        gameplay: "BLOCKED",
        hardware: "BLOCKED",
        firstFailure: { code: "PREEXISTING_QA_EVIDENCE_DIR", owner: "E5" },
        firstFailedStage: "boot",
      };
      save(modeName, verdict);
      return verdict;
    }
  }
  const processResult = spawnSync(
    process.execPath,
    ["scripts/national-qa/browser-gameplay.mjs", ...config.args],
    {
      env: { ...process.env, NATIONAL_GPU_CANDIDATE_SHA: head },
      encoding: "utf8",
      timeout: 205_000,
      maxBuffer: 4_000_000,
    },
  );
  // Raw console, private network diagnostics and packet details stay local.
  const privateLogs = join(root, "private-logs");
  mkdirSync(privateLogs, { recursive: true });
  writeFileSync(
    join(privateLogs, modeName + ".log"),
    (processResult.stdout ?? "") + "\n" + (processResult.stderr ?? ""),
    { mode: 0o600 },
  );
  let report = null;
  try {
    report = JSON.parse(readFileSync(join(folder, "acceptance.json"), "utf8"));
  } catch {
    // A failed boot often cannot write a report. Never invent one.
  }
  const imageEvidence = screenshots(folder);
  const verdict = classifySoloOrLegacy({
    mode: modeName,
    report,
    exitCode: processResult.status,
    expectedSha: head,
    screenshotLabels: imageEvidence.labels,
  });
  verdict.screenshotEvidence = imageEvidence.manifest;
  if (processResult.error) {
    verdict.gameplay = "FAIL";
    if (!verdict.firstFailedStage) {
      verdict.firstFailure = {
        code:
          processResult.error.code === "ETIMEDOUT"
            ? "CHROMIUM_PROCESS_TIMEOUT"
            : "CHROMIUM_PROCESS_FAILED",
        owner: "E5",
      };
    }
  }
  save(modeName, verdict);
  return verdict;
}
const cdpPorts = () => {
  const source = process.env.NATIONAL_QA_PRIVATE_CDP_PORTS ?? "";
  const numbers = source.split(",").map((x) => Number(x.trim()));
  return numbers.length === 3 &&
    numbers.every((n) => Number.isSafeInteger(n) && n > 0 && n <= 65535) &&
    new Set(numbers).size === 3
    ? numbers
    : null;
};
function sessionObservation(port) {
  // This function ONLY observes a running, independently logged-in profile.
  // It never sets cookies, authorizes an actor or starts a fake Solo match.
  return Promise.race([
    (async () => {
      const res = await fetch("http://127.0.0.1:" + port + "/json/list", {
        signal: AbortSignal.timeout(2000),
      });
      if (!res.ok) throw Error("CDP_HTTP_UNAVAILABLE");
      const tabs = await res.json();
      const page = tabs.find(
        (t) => t.type === "page" && typeof t.webSocketDebuggerUrl === "string",
      );
      if (!page) throw Error("REAL_CDP_PAGE_MISSING");
      const ws = new WebSocket(page.webSocketDebuggerUrl);
      await new Promise((resolveOpen, rejectOpen) => {
        ws.addEventListener("open", resolveOpen, { once: true });
        ws.addEventListener("error", rejectOpen, { once: true });
      });
      let serial = 0;
      const pending = new Map();
      ws.addEventListener("message", (event) => {
        let data;
        try {
          data = JSON.parse(String(event.data));
        } catch {
          return;
        }
        if (!pending.has(data.id)) return;
        const entry = pending.get(data.id);
        pending.delete(data.id);
        if (data.error) entry.reject(Error("CDP_RESPONSE_ERROR"));
        else entry.resolve(data.result);
      });
      const send = (method, params = {}) =>
        new Promise((resolveSend, rejectSend) => {
          const id = ++serial;
          pending.set(id, { resolve: resolveSend, reject: rejectSend });
          ws.send(JSON.stringify({ id, method, params }));
        });
      try {
        const browser = await send("Browser.getVersion");
        const state = await send("Runtime.evaluate", {
          // E4 must expose authenticated host-projection identity; the absence
          // is a legitimate blocker, never consent for fabricated attributes.
          expression: `(() => {
            const p = document.querySelector('[data-national-trusted-session]');
            const canvas = [...document.querySelectorAll('canvas')]
              .find(c => c.getBoundingClientRect().width > 150);
            const r = canvas?.getBoundingClientRect();
            const status = document.getElementById(
              'trusted-national-projection-status',
            );
            const visibleProjection =
              status?.dataset.trustedNationalMap === 'visible';
            const tickText = p?.getAttribute('data-national-projection-tick');
            const validatedTick =
              tickText && /^[0-9]+$/.test(tickText) ? Number(tickText) : null;
            return {
              principalId: p?.getAttribute('data-national-principal-id') ?? null,
              matchId: p?.getAttribute('data-national-match-id') ?? null,
              displayedHostAdmission:
                p?.getAttribute('data-national-host-admitted') === 'true',
              displayedProjectionTick: validatedTick,
              displayedSpectator:
                p?.getAttribute('data-national-spectator') === 'true',
              visibleMapRendered: !!r && r.width > 150 &&
                r.height > 100 && visibleProjection,
            };
          })()`,
          returnByValue: true,
        });
        const ui = state.result?.value ?? {};
        // A DOM attribute is only a UI observation; never trust it as
        // server authority or verified account admission.
        return {
          cdpPort: port,
          connected: true,
          browserTargetType: page.type,
          browserProduct: browser.product ?? null,
          principalId: ui.principalId,
          matchId: ui.matchId,
          hostAdmitted: false,
          serverOwnedProjection: false,
          serverTick: Number.isSafeInteger(ui.displayedProjectionTick)
            ? ui.displayedProjectionTick
            : null,
          visibleMapRendered: ui.visibleMapRendered === true,
          spectator: ui.displayedSpectator,
          displayClaimsHostAdmission: ui.displayedHostAdmission === true,
        };
      } finally {
        ws.close();
      }
    })(),
    new Promise((_, rejectTimeout) =>
      setTimeout(
        () => rejectTimeout(Error("PRIVATE_CDP_OBSERVATION_TIMEOUT")),
        8000,
      ),
    ),
  ]);
}
async function privateObservation() {
  const ports = cdpPorts();
  if (!ports) {
    const verdict = {
      gameplay: "BLOCKED",
      hardware: "BLOCKED",
      firstFailure: "THREE_AUTHENTICATED_BROWSER_CDP_PORTS_MISSING",
      owner: "E2/E4/E5",
    };
    save("private-national", verdict);
    return verdict;
  }
  const observations = await Promise.allSettled(ports.map(sessionObservation));
  if (observations.some((x) => x.status !== "fulfilled")) {
    const verdict = {
      gameplay: "BLOCKED",
      hardware: "BLOCKED",
      firstFailure: "REAL_THREE_CDP_BROWSERS_UNREACHABLE",
      owner: "E2/E5",
    };
    save("private-national", verdict);
    return verdict;
  }
  const seats = observations.map((x) => x.value);
  const topology = verifyPrivateBrowserTopology(seats);
  // Merely observing three browser tabs does not prove authenticated server
  // ownership. E2 admission, E3 private bytes and E6 independent host witness
  // must be produced by their real authorities. No fake accession or WAR.
  const verdict = classifyPrivateNational({
    topology,
    joined: false,
    bilateralAccession: false,
    warReceipt: false,
    opponentPeace: false,
    privateViewsDifferent: false,
    reconnectRevokedOldSocket: false,
    spectatorDenied: false,
    hostWitnessVerified: false,
  });
  save("private-national", verdict);
  return verdict;
}
let failCount = 0;
for (const name of modes) {
  const verdict =
    name === "private-national" ? await privateObservation() : runLocal(name);
  if (verdict.gameplay !== "PASS") failCount++;
}
// Exit status is a machine gate, never a substitute for the evidence JSON.
if (failCount) process.exitCode = 1;
